"""Bake-off scoreboard script for DocSearch conformance suite.

Parses JUnit XML report generated by pytest (--junitxml=...) and prints
a categorized scorecard across the 8 functional specification areas.

Usage:
    python conformance/score.py [path/to/results.xml]
"""

import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Dict, List, Tuple

# Mapping of test prefix or function name to functional evaluation area
AREAS = {
    "1. Health & Lifecycle": ["test_01"],
    "2. Auth & Security": ["test_02", "test_03", "test_19"],
    "3. Collections": ["test_04"],
    "4. Documents & Ingestion": [
        "test_05",
        "test_06",
        "test_07",
        "test_08",
        "test_09",
        "test_10",
        "test_23",
    ],
    "5. Retrieval & RAG": ["test_11", "test_12", "test_17", "test_20", "test_24"],
    "6. Access Control & ACL": ["test_13", "test_14", "test_15"],
    "7. Administration": ["test_21"],
    "8. Error Hygiene & Safety": ["test_16", "test_18", "test_22"],
}


def find_area_for_test(test_name: str) -> str:
    for area, patterns in AREAS.items():
        if any(p in test_name for p in patterns):
            return area
    return "Other"


def parse_junit_xml(xml_path: Path) -> Tuple[Dict[str, Dict[str, int]], Dict[str, int]]:
    tree = ET.parse(xml_path)
    root = tree.getroot()

    area_scores: Dict[str, Dict[str, int]] = {
        area: {"passed": 0, "failed": 0, "skipped": 0, "total": 0} for area in AREAS
    }
    totals = {"passed": 0, "failed": 0, "skipped": 0, "total": 0}

    # Handle both <testsuites><testsuite> and root <testsuite>
    testcases = root.findall(".//testcase") if root.tag != "testcase" else [root]

    for tc in testcases:
        name = tc.get("name", "")
        area = find_area_for_test(name)

        has_failure = tc.find("failure") is not None or tc.find("error") is not None
        has_skip = tc.find("skipped") is not None

        if has_failure:
            status = "failed"
        elif has_skip:
            status = "skipped"
        else:
            status = "passed"

        totals[status] += 1
        totals["total"] += 1

        if area in area_scores:
            area_scores[area][status] += 1
            area_scores[area]["total"] += 1

    return area_scores, totals


def main() -> None:
    if len(sys.argv) > 1:
        xml_path = Path(sys.argv[1])
    else:
        results_dir = Path(__file__).resolve().parent / "results"
        xml_files = list(results_dir.glob("*.xml")) if results_dir.exists() else []
        if not xml_files:
            print("No JUnit XML results file specified or found in conformance/results/.")
            print("Run pytest with: pytest conformance -m contract --junitxml=conformance/results/report.xml")
            sys.exit(1)
        xml_path = xml_files[0]

    if not xml_path.exists():
        print(f"Error: File not found: {xml_path}")
        sys.exit(1)

    area_scores, totals = parse_junit_xml(xml_path)

    print("\n" + "=" * 76)
    print(f"DocSearch Conformance Scoreboard: {xml_path.name}")
    print("=" * 76)
    print(f"{'Functional Area':<32} | {'Passed':<8} | {'Failed':<8} | {'Skipped':<8} | {'Rate':<8}")
    print("-" * 76)

    for area, stats in area_scores.items():
        pass_rate = (
            f"{(stats['passed'] / stats['total']) * 100:.1f}%"
            if stats["total"] > 0
            else "N/A"
        )
        print(
            f"{area:<32} | {stats['passed']:<8} | {stats['failed']:<8} | {stats['skipped']:<8} | {pass_rate:<8}"
        )

    print("-" * 76)
    overall_rate = (
        f"{(totals['passed'] / totals['total']) * 100:.1f}%"
        if totals["total"] > 0
        else "N/A"
    )
    print(
        f"{'TOTAL':<32} | {totals['passed']:<8} | {totals['failed']:<8} | {totals['skipped']:<8} | {overall_rate:<8}"
    )
    print("=" * 76 + "\n")


if __name__ == "__main__":
    main()
